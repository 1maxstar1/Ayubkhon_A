  function B(kind, s) { this.kind = kind; this.s = ' ' + s + ' '; this.slots = {}; this.attrs = { kind: kind }; this.expl = []; }
  B.prototype.put = function (name, val, lvl, label) {
    if (val === null || val === undefined || val === '') return;
    val = String(val);
    var o = this.slots[name];
    if (o) {
      var vs = o.v.split(',');
      if (vs.indexOf(val) < 0) { vs.push(val); vs.sort(); o.v = vs.join(','); o.lab = (label || name) + ' ' + o.v; }
      this.attrs[name] = o.v;
      return;
    }
    this.slots[name] = { v: val, l: lvl, lab: label ? label + ' ' + val : name + ' ' + val };
    this.attrs[name] = val;
  };
  B.prototype.seq = function (name, val, lvl, label) {
    var o = this.slots[name];
    if (o) { o.v += ',' + val; o.lab = label + ' ' + o.v; this.attrs[name] = o.v; return; }
    this.slots[name] = { v: String(val), l: lvl, lab: label + ' ' + val };
    this.attrs[name] = String(val);
  };
  B.prototype.get = function (name) { return this.slots[name] ? this.slots[name].v : null; };
  B.prototype.take = function (re, fn) {
    var self = this;
    this.s = this.s.replace(re, function () {
      var m = Array.prototype.slice.call(arguments, 0, arguments.length - 2);
      var r = fn.call(self, m);
      if (r === false) return m[0];
      if (typeof r === 'string' && r.charAt(0) === '=') return r.slice(1);
      var lead = m[0].charAt(0);
      return (/[^А-ЯЁA-Z0-9]/.test(lead) && r !== 'all') ? lead + ' ' : ' ';
    });
  };
